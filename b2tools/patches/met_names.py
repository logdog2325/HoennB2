"""Met locations above Black 2's 154 place names: Pokémon traded from Pokémon Pearl NDS (the sister project PearlB2,
agreed 2026-10-18, notes/LINK.md) carry Sinnoh's met locations on place-name lines 154-264.

- apply_code: MetLocation_GetNameIndex (arm9 0x02035fac, pokebw2 src/system/pml_met_data.c) returns line 2 ("Faraway
  place") for every location from 154 to 30000. Its `cmp r0, #154; bcc` becomes `lsrs r3, r0, #9; beq`: locations
  0-511 show their own line (PearlB2 found and tested it in game: a Piplup met in Twinleaf, location 154, showed
  "Faraway place", then "Twinleaf Town").
- Text: system text 109 gets Sinnoh's names on lines 154-264 (data/sinnoh_places.json) and is padded to 512 lines with
  Black 2's own "Faraway place", so a location with no name still reads as in Black 2.
  `python3 met_names.py --text` writes src/text/overrides_sinnoh_places.json (patches/text.py appends the lines);
  apply() checks it is current.
All three versions alike."""
import json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
ARM9 = 0x02004000
AT = 0x02035fac + 6
OLD, NEW = bytes.fromhex('9a281ad3'), bytes.fromhex('430a1ad0')     # cmp r0, #0x9a; bcc  ->  lsrs r3, r0, #9; beq
B2_PLACES, LINES_MAX = 154, 512
FARAWAY = 'Faraway place'
TEXT = os.path.join(ROOT, 'src', 'text', 'overrides_sinnoh_places.json')


def text_lines():
    lines = {int(k): v for k, v in json.load(open(os.path.join(ROOT, 'data', 'sinnoh_places.json')))['lines'].items()}
    assert min(lines) == B2_PLACES and max(lines) < LINES_MAX, (min(lines), max(lines))
    return {str(i): lines.get(i, FARAWAY) for i in range(B2_PLACES, LINES_MAX)}


def write_text():
    out = {'_doc': 'Generated by b2tools/patches/met_names.py --text: Sinnoh place names (Pokémon Pearl NDS) on lines '
                   '154-264 of system text 109, padding to line 511 with "Faraway place".',
           'system/0109_place_names.txt': text_lines()}
    open(TEXT, 'w', encoding='utf-8').write(json.dumps(out, indent=1, ensure_ascii=False) + '\n')


def apply(files):
    cur = json.load(open(TEXT, encoding='utf-8'))['system/0109_place_names.txt'] if os.path.exists(TEXT) else None
    assert cur == text_lines(), 'met_names: src/text/overrides_sinnoh_places.json is stale: python3 met_names.py --text'
    return f'met_names: place lines {B2_PLACES}-{LINES_MAX - 1} (Sinnoh 154-264 + "{FARAWAY}") in system text 109'


def apply_code(code):
    p = os.path.join(code, 'arm9.bin')
    d = bytearray(open(p, 'rb').read())
    o = AT - ARM9
    if bytes(d[o:o + 4]) != NEW:
        assert bytes(d[o:o + 4]) == OLD, f'met_names: unexpected bytes at {AT:#x}: {bytes(d[o:o + 4]).hex()}'
        d[o:o + 4] = NEW
        if os.path.islink(p): os.unlink(p)
        open(p + '.tmp', 'wb').write(d); os.replace(p + '.tmp', p)
    return f'met_names: MetLocation_GetNameIndex shows locations 0-{LINES_MAX - 1} by their own line'


if __name__ == '__main__' and '--text' in sys.argv:
    write_text(); print('wrote', TEXT)
