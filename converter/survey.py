"""Survey every Sapphire map in pokeruby: what each needs, so the rest of Hoenn can be planned and batched.

    python3 survey.py ../external/pokeruby > ../notes/HOENN_SURVEY.md   (also writes ../data/hoenn_maps.json)

Per map: type, size, tilesets, elevation levels used (blockdata bits 12-15), behaviours present (water, ledges,
tall grass, ...), how many of its metatiles converter/metatiles.json already knows, events, script size, trainers.
"""
import sys, os, json, re, glob, collections
import numpy as np
from gba import Repo

root = sys.argv[1]
r = Repo(root)
here = os.path.dirname(os.path.abspath(__file__))
table = json.load(open(os.path.join(here, 'metatiles.json')))
wild = json.load(open(f'{root}/src/data/wild_encounters.json'))['wild_encounter_groups'][0]['encounters']
wild_maps = {e['map'] for e in wild}

# pokeruby behaviour groups (include/constants/metatile_behaviors.h ranges as used by export.py/classify)
def behaviour_group(b):
    if b in (0x02, 0x03): return 'tall_grass'
    if 0x10 <= b <= 0x17 or b in (0x18, 0x19, 0x1A, 0x1B): return 'water'
    if 0x38 <= b <= 0x3F: return 'ledge'
    if b in (0x06, 0x07, 0x21, 0x23, 0x24): return 'sand_or_ash'
    if 0x60 <= b <= 0x6F: return 'warp_tile'     # doors, stairs, cave holes (approximate group)
    if 0x40 <= b <= 0x4F: return 'slide_or_ice'
    return None

maps = []
for mj_path in sorted(glob.glob(f'{root}/data/maps/*/map.json')):
    name = os.path.basename(os.path.dirname(mj_path))
    mj = json.load(open(mj_path))
    if mj['layout'] not in r.layouts: continue
    try:
        g, l = r.layout_grid(mj['layout'])
    except Exception:
        continue
    prim, sec = l['primary_tileset'], l['secondary_tileset']
    raw = g.astype(np.uint32)
    mt = raw & 0x3FF; elev = (raw >> 12) & 0xF
    # behaviours
    groups = collections.Counter()
    known = 0; unique = set(int(v) for v in np.unique(mt))
    try:
        p = r.load_tileset(prim); s = r.load_tileset(sec)
        for m in unique:
            a = p['attr'] if m < 512 else s['attr']; i = m if m < 512 else m - 512
            b = int(a[i] & 0xFF) if i < len(a) else 0
            gb = behaviour_group(b)
            if gb: groups[gb] += int((mt == m).sum())
    except Exception:
        pass
    for m in unique:
        ts = prim if m < 512 else sec
        if f'{m:03x}' in table.get(ts, {}): known += 1
    scripts = os.path.join(os.path.dirname(mj_path), 'scripts.inc')
    script_lines = sum(1 for _ in open(scripts)) if os.path.exists(scripts) else 0
    trainers = sum(1 for o in mj.get('object_events', []) if o.get('trainer_type', 'TRAINER_TYPE_NONE') != 'TRAINER_TYPE_NONE')
    maps.append(dict(name=name, type=mj.get('map_type'), w=int(g.shape[1]), h=int(g.shape[0]), primary=prim,
                     secondary=sec, elevations=sorted(int(v) for v in np.unique(elev)),
                     features=dict(groups), metatiles=len(unique), known_metatiles=known,
                     npcs=len(mj.get('object_events', [])), trainers=trainers, warps=len(mj.get('warp_events', [])),
                     signs=len(mj.get('bg_events', [])), triggers=len(mj.get('coord_events', [])),
                     script_lines=script_lines, connections=[c['map'] for c in (mj.get('connections') or [])],
                     wild=upper in wild_maps if (upper := mj.get('id')) else False))
json.dump(maps, open(os.path.join(here, '..', 'data', 'hoenn_maps.json'), 'w'), indent=1)

by_type = collections.defaultdict(list)
for m in maps: by_type[m['type']].append(m)
print('# Sapphire map survey (generated by converter/survey.py)\n')
print(f'{len(maps)} maps in pokeruby with a layout.\n')
print('| Map type | Maps | Tiles (sum of w×h) | NPCs | Trainers | Script lines | Multi-level (elevations > 1) | With water |')
print('|---|---|---|---|---|---|---|---|')
for t, ms in sorted(by_type.items(), key=lambda kv: -len(kv[1])):
    print(f"| {t} | {len(ms)} | {sum(m['w'] * m['h'] for m in ms)} | {sum(m['npcs'] for m in ms)} | "
          f"{sum(m['trainers'] for m in ms)} | {sum(m['script_lines'] for m in ms)} | "
          f"{sum(1 for m in ms if len(set(m['elevations']) - {0, 15}) > 1)} | {sum(1 for m in ms if m['features'].get('water'))} |")
ts = collections.Counter((m['primary'], m['secondary']) for m in maps)
print(f'\n{len(ts)} tileset pairs; {len({m["secondary"] for m in maps})} secondary tilesets. Most used:\n')
for (p, s), n in ts.most_common(12): print(f'- {p} + {s}: {n} maps')
outdoor = [m for m in maps if m['type'] in ('MAP_TYPE_TOWN', 'MAP_TYPE_CITY', 'MAP_TYPE_ROUTE', 'MAP_TYPE_OCEAN_ROUTE')]
print(f'\nOutdoor maps ({len(outdoor)}), largest:\n')
for m in sorted(outdoor, key=lambda m: -m['w'] * m['h'])[:12]:
    print(f"- {m['name']}: {m['w']}×{m['h']} tiles ({(m['w'] + 31) // 32}×{(m['h'] + 31) // 32} chunks), "
          f"features {m['features']}, elevations {m['elevations']}")
