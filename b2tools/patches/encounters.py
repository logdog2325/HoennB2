"""Assemble src/encounters/NNNN_*.s with the decomp's encounter macros and put each into a/1/2/7 as entry NNNN
(sizes kept; most files are generated by converter/gen_encounters.py)."""
import os, sys, glob, subprocess, tempfile
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import narcio, version   # Ruby: src/encounters/ruby/NNNN_*.s replace Sapphire's files (version.overlay)
ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
DECOMP = os.path.abspath(os.path.join(ROOT, 'external', 'pokebw2'))
LLVM = '/opt/homebrew/opt/llvm/bin'

def apply(files):
    entries = narcio.load(files, 127)
    done = []
    for src in version.overlay(os.path.join(ROOT, 'src', 'encounters'), '*.s'):
        num = int(os.path.basename(src)[:4])
        with tempfile.TemporaryDirectory() as t:
            o, b = os.path.join(t, 'x.o'), os.path.join(t, 'x.bin')
            only = os.environ.get('HOENN_TEST_NO_WILD_FILES')        # e.g. "99,101": only these files lose their grass
            if os.environ.get('HOENN_TEST_NO_WILD') or (only and num in [int(x) for x in only.split(',')]):
                import re
                tmp = os.path.join(t, 'src.s')
                # HOENN_TEST_NO_WILD_SURF=1 (caves_east): no surfing battles either (cave water tests)
                pat = r'(grass|surf)=\d+' if os.environ.get('HOENN_TEST_NO_WILD_SURF') else r'(grass)=\d+'
                open(tmp, 'w').write(re.sub(pat, r'\1=0', open(src).read()))
                src = tmp
            subprocess.run([f'{LLVM}/clang', '--target=armv5te-none-eabi', '-x', 'assembler-with-cpp', '-c',
                            '-I', f'{DECOMP}/include', '-D', 'BLACK2', '-o', o, os.path.abspath(src)], check=True, cwd=DECOMP)
            subprocess.run([f'{LLVM}/llvm-objcopy', '-O', 'binary', o, b], check=True)
            new = open(b, 'rb').read()
        if num >= len(entries) and version.is_emerald():   # (emerald_caves 2026-10-12) Emerald's own caves' tables: new
            assert num == len(entries), f'encounter file {num}: the new files must follow a/1/2/7\'s last ({len(entries) - 1})'
            entries.append(new)                             # files after Black 2's (data/emerald/hoenn_encounters.json;
            done.append(f'{num} ({len(new)} B, new)')       # inside the archive's fixed reserve: the ROM layout stays)
            continue
        assert len(new) == len(entries[num]), f'encounter file {num}: {len(new)} bytes, original {len(entries[num])} ' \
            '(keep the size: savestates cache the archive layout, converter/gen_encounters.py)'
        entries[num] = new
        done.append(f'{num} ({len(new)} B)')
    narcio.save(files, 127, entries)
    return 'encounters ' + ', '.join(done)
